#!/usr/bin/env python3
"""Writes lib/geom/strokefont_data.zig: the glyphs of Graven's stroke font.

    python3 scripts/strokefont.py futural.jhf > lib/geom/strokefont_data.zig

Printable ASCII is Hershey's Roman Simplex ("futural" in the usual .jhf
distribution; taken from the archive embedded in the Hershey-Fonts 2.1.0
package on PyPI). The other glyphs a dimension needs (degree, diameter,
plus-minus, times, minus, arrows, primes, middle dot) are drawn here, in
the same units and the same encoding, so the font is all of a piece.

The Hershey fonts were originally created by Dr. A. V. Hershey while
working at the U. S. National Bureau of Standards.

Encoding (Hershey's): each glyph is a string of character pairs, each an
offset from 'R'; the first pair is the glyph's left and right edges, the
rest its points (x, y, with y down), " R" lifting the pen. The cap line is
at y = -12, the baseline at 9, the x-height line at -5.
"""
import math
import sys


def enc(v):
    v = int(round(v))
    assert -40 <= v <= 40, v
    return chr(ord("R") + v)


def glyph(left, right, strokes):
    """A glyph from its edges and polylines of (x, y) points."""
    out = enc(left) + enc(right)
    for i, s in enumerate(strokes):
        if i:
            out += " R"
        for x, y in s:
            out += enc(x) + enc(y)
    return out


def arc(cx, cy, rx, ry, a0, a1, step=30):
    """Points of an elliptical arc, degrees, y down (angles turn clockwise)."""
    n = max(2, int(math.ceil(abs(a1 - a0) / step)) + 1)
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / (n - 1))),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / (n - 1)))) for i in range(n)]


# Drawn here (codepoint, left, right, strokes). Hershey units: digits are
# 20 wide, the cap height 21.
EXTRA = [
    (0x00B0, -5, 5, [arc(0, -9, 3, 3, 0, 360)]),                       # ° degree
    (0x2300, -12, 12, [arc(0, -1.5, 8, 8, 0, 360, 24), [(-9, 9), (9, -12)]]),  # ⌀ diameter
    (0x00D8, -12, 12, [arc(0, -1.5, 8, 10.5, 0, 360, 24), [(-9, 9), (9, -12)]]),  # Ø (as a diameter is often typed)
    (0x00B1, -13, 13, [[(0, -11), (0, 3)], [(-8, -4), (8, -4)], [(-8, 9), (8, 9)]]),  # ±
    (0x00D7, -11, 11, [[(-6, -6), (6, 6)], [(6, -6), (-6, 6)]]),        # × times
    (0x2212, -13, 13, [[(-9, 0), (9, 0)]]),                              # − minus
    (0x2194, -14, 14, [[(-11, 0), (11, 0)], [(-6, -4), (-11, 0), (-6, 4)], [(6, -4), (11, 0), (6, 4)]]),  # ↔
    (0x2195, -7, 7, [[(0, -12), (0, 9)], [(-4, -7), (0, -12), (4, -7)], [(-4, 4), (0, 9), (4, 4)]]),     # ↕
    (0x2032, -4, 4, [[(1, -12), (-1, -6)]]),                             # ′ prime
    (0x2033, -6, 6, [[(-1, -12), (-3, -6)], [(3, -12), (1, -6)]]),       # ″ double prime
    (0x00B7, -4, 4, [arc(0, -1.5, 1, 1, 0, 360, 90)]),                   # · middle dot
    (0x2220, -12, 12, [[(9, -10), (-9, 9), (10, 9)]]),                   # ∠ angle
    (0x2245, -13, 13, [[(-9, -6), (-7, -8.5), (-4, -9.5), (-1, -8.5), (1, -7), (4, -5.5), (7, -6.5), (9, -9)], [(-9, -2), (9, -2)], [(-9, 3), (9, 3)]]),  # ≅ congruent (equal angles)
    # Constraint marks, in the Private Use Area (no Unicode symbol fits):
    # tangent, a line touching an arc; on object, a point on an arc.
    (0xE000, -15, 15, [arc(0, 4, 12, 12, 180, 360, 12), [(-13, -8), (13, -8)]]),
    (0xE001, -15, 15, [arc(0, 7, 12, 12, 180, 360, 12), arc(0, -5, 3, 3, 0, 360, 30), arc(0, -5, 2, 2, 0, 360, 45), arc(0, -5, 1, 1, 0, 360, 90)]),
    (0x03B8, -9, 9, [arc(0, -1.5, 6, 10.5, 0, 360, 24), [(-6, -1.5), (6, -1.5)]]),  # θ theta (a set of equal angles)
]


def main():
    lines = [l for l in open(sys.argv[1]).read().split("\n")[1:] if l.strip()]
    assert len(lines) == 96, len(lines)
    print("//! Generated by scripts/strokefont.py; do not edit. The glyphs of the")
    print("//! stroke font (see strokefont.zig): Hershey's Roman Simplex for ASCII,")
    print("//! the rest drawn to match. The Hershey fonts were originally created")
    print("//! by Dr. A. V. Hershey while working at the U. S. National Bureau of")
    print("//! Standards.")
    print()
    print("/// Glyphs for ' ' to DEL (U+0020 to U+007F), in order.")
    print("pub const ascii = [_][]const u8{")
    for l in lines:
        n = int(l[5:8])
        data = l[8:]
        assert len(data) == 2 * n
        print("    " + zstr(data) + ",")
    print("};")
    print()
    print("/// The other glyphs, by codepoint.")
    print("pub const extra = [_]struct { cp: u21, g: []const u8 }{")
    for cp, left, right, strokes in EXTRA:
        print("    .{ .cp = 0x%04X, .g = %s }," % (cp, zstr(glyph(left, right, strokes))))
    print("};")


def zstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
